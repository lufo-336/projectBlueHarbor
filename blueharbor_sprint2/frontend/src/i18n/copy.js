/** Traduce un messaggio d'errore backend in EN; altrimenti lo restituisce invariato. */
export function translateApiError(message, lang) {
  if (lang !== 'en' || !message) return message;
  const exact = ERR_EXACT[message];
  if (exact) return exact;
  for (const [re, fn] of ERR_PATTERNS) {
    const m = message.match(re);
    if (m) return fn(m);
  }
  return message; // fallback morbido: resta in italiano
}

/** Risolve una chiave "a.b.c" nel dizionario; valore stringa o funzione(params). */
export function translate(dict, key, params) {
  const val = key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), dict);
  if (val == null) return key; // chiave mancante: mostra la chiave (visibile, non mente)
  return typeof val === 'function' ? val(params || {}) : val;
}

/** Lingua iniziale: preferenza salvata, altrimenti lingua del browser (fallback IT). */
export function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved === 'it' || saved === 'en') return saved;
    const nav = (navigator.language || '').toLowerCase();
    return nav.startsWith('en') ? 'en' : 'it';
  } catch {
    return 'it';
  }
}
